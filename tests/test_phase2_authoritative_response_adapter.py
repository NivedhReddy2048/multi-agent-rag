def test_1_no_additional_llm_generation():
    """Test 1: Verify AgentResponseAdapter composes EducationalResponse without invoking any LLM manager or provider."""
    result = AgentResult(
        content="Authoritative answer generated by Orchestrator.",
        confidence=88,
        sources=[{"title": "Doc A", "url": "", "provider": "uploaded_documents", "source_type": "internal_document"}],
        metadata={"response_status": "SUCCESS", "provider": "gemini", "model": "gemini-2.5-flash"},
        success=True,
    )

    with patch("core.llm_manager.LLMManager.generate") as mock_llm_gen:
        edu_resp = agent_response_adapter.compose_from_agent_result(result)
        mock_llm_gen.assert_not_called()
        assert edu_resp["ai_explanation"] == "Authoritative answer generated by Orchestrator."


