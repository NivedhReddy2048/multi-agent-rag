def test_8_legacy_full_graph_compatibility():
    """Test 8: Verify legacy execution_mode="full" still permits existing KnowledgeSynthesizer -> ResponseComposer behavior."""
    from graph.nodes.synthesis_node import knowledge_synthesis_node
    from graph.state import EKIPGraphState

    state = EKIPGraphState(
        question="What is quantum computing?",
        execution_mode="full",
        skip_synthesis=False,
        provider_metadata={
            "verified_collection": {
                "query": "What is quantum computing?",
                "verified_results": [],
                "overall_confidence": 0.9,
                "overall_agreement": 0.9,
                "verification_summary": "Verified",
            }
        }
    )

    with patch("core.synthesis.knowledge_synthesizer.synthesize") as mock_synth, \
         patch("core.synthesis.response_composer.compose_response") as mock_comp:

        mock_synth.return_value = MagicMock()
        mock_comp_resp = MagicMock()
        mock_comp_resp.dict.return_value = {"ai_explanation": "Legacy full graph response"}
        mock_comp_resp.learning_summary = "Legacy summary"
        mock_comp_resp.providers_used = ["gemini"]
        mock_comp_resp.confidence = 0.9
        mock_comp.return_value = mock_comp_resp

        updated_state = knowledge_synthesis_node(state)
        mock_synth.assert_called_once()
        mock_comp.assert_called_once()
        assert updated_state.educational_response == {"ai_explanation": "Legacy full graph response"}
