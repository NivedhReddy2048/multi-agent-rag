def test_6_insufficient_evidence_status():
    """Test 6: Verify behavior when response_status == INSUFFICIENT_EVIDENCE (no fake categories/sources populated)."""
    insuff_text = "I couldn't find enough information in your indexed documents to create a document-grounded answer."
    result = AgentResult(
        content=insuff_text,
        confidence=0,
        sources=[{"title": "Stale Source", "url": "", "provider": "uploaded_documents"}],
        metadata={"response_status": "INSUFFICIENT_EVIDENCE", "failure_reason": "INSUFFICIENT_EVIDENCE"},
        success=False,
    )
    edu_resp = agent_response_adapter.compose_from_agent_result(result)

    assert edu_resp["ai_explanation"] == insuff_text
    assert edu_resp["response_status"] == "INSUFFICIENT_EVIDENCE"
    assert len(edu_resp["citations"]) == 0
    assert len(edu_resp["uploaded_notes"]) == 0
    assert len(edu_resp["trusted_web"]) == 0
    assert "Insufficient document evidence" in edu_resp["learning_summary"]


